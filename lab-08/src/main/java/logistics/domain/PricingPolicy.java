package logistics.domain;

/**
 * Protected Variations: ставки, які можуть змінюватись (ціна за кг, % страховки),
 * сховані за інтерфейсом. Завтра ставки можуть братись з БД або конфігу —
 * доменні класи не зміняться.
 */
public interface PricingPolicy {

    /** Базова ставка за 1 кг вантажу, грн. */
    double ratePerKg();

    /** Страховий відсоток від заявленої вартості (0.005 = 0.5%). */
    double insuranceRate();
}
